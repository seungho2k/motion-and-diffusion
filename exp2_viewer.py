import datetime as dt
import json
import os
import sys
import threading
import time
from dataclasses import asdict

import imageio.v2 as imageio
import numpy as np
import viser

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "src"))
from amdm_runtime import DECODE_MODES, AMDMRuntime, GenParams  # noqa: E402
from camera import TrackCam, orbit_from  # noqa: E402
from schedule import DipSchedule, PulseSchedule, RampSchedule  # noqa: E402
from viewer_common import CurvePlot, PersistentGui  # noqa: E402

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "outputs")
VIDEO_W, VIDEO_H, FPS = 1080, 1350, 30


def main():
    rt = AMDMRuntime("lafan1")
    T = rt.T
    server = viser.ViserServer(port=8080)
    server.gui.configure_theme(dark_mode=True)
    server.scene.set_up_direction("+y")
    # Tracking is baked into the coordinates sent each frame: the tracked joint is
    # subtracted from every point server-side, so it is exactly at the origin in
    # the very same message that carries the new pose (no frame where pose and
    # offset disagree). The camera stays put and looks at the origin.
    grid = server.scene.add_grid("/grid", width=40, height=40, plane="xz", cell_size=0.5, section_size=2.0,
                                 cell_color=(40, 40, 40), section_color=(70, 70, 70), shadow_opacity=0.0,
                                 infinite_grid=True, fade_distance=200.0, fade_from="origin")

    state = {"res": None, "frame": 0, "playing": True}
    lock = threading.Lock()

    # ------------------------------------------------------------------ GUI
    with server.gui.add_folder("Schedule  τ(f)"):
        g_frames = server.gui.add_slider("frames", 60, 1800, 30, 900)
        g_stype = server.gui.add_dropdown("type", ("pulses", "ramp", "dip"), initial_value="pulses",
                                          hint="pulses: clean motion with short pulses back toward noise. "
                                               "ramp: clean, then tau grows to its maximum at the end. "
                                               "dip: noise with one recognition window.")
        g_rfade = server.gui.add_slider("ramp in end", 0.0, 0.99, 0.01, 0.2,
                                        hint="Opening: tau falls from its max to base by this fraction (0 = no opening).")
        g_rstart = server.gui.add_slider("ramp out start", 0.0, 0.99, 0.01, 0.7,
                                         hint="Ending: tau starts to grow back at this fraction of the clip.")
        g_rpeak = server.gui.add_slider("ramp max τ", 0.5, float(T), 0.5, float(T))
        g_rcurve = server.gui.add_dropdown("ramp curve", ("linear", "ease in", "ease out", "ease in-out",
                                                          "exponential"), initial_value="ease in")
        g_rpower = server.gui.add_slider("ramp steepness", 0.2, 10.0, 0.1, 2.0,
                                         hint="Power for ease curves / rate for exponential.")
        g_rbase = server.gui.add_slider("ramp base τ", 0.0, float(T), 0.1, 0.0)
        g_pframes = server.gui.add_text("pulse frames", "",
                                        hint="Comma-separated start frames, e.g. 150, 420, 700. Empty = evenly spaced.")
        g_pcount = server.gui.add_slider("pulse count", 0, 20, 1, 3)
        g_ppeak = server.gui.add_slider("pulse peak τ", 0.5, float(T), 0.5, 12.0)
        g_pattack = server.gui.add_slider("pulse attack (fr)", 0, 20, 1, 2)
        g_pdecay = server.gui.add_slider("pulse decay (fr)", 1, 90, 1, 6)
        g_pbase = server.gui.add_slider("base τ", 0.0, float(T), 0.1, 0.0)
        g_high = server.gui.add_slider("τ high", 0.0, float(T), 0.1, float(T))
        g_low = server.gui.add_slider("τ low", 0.0, float(T), 0.1, 0.0)
        g_center = server.gui.add_slider("center", 0.0, 1.0, 0.01, 0.5)
        g_width = server.gui.add_slider("half width (fr)", 2.0, 900.0, 1.0, 600.0)
        g_sharp = server.gui.add_slider("sharpness", 0.5, 12.0, 0.1, 2.0)
    with server.gui.add_folder("Generation"):
        g_seed = server.gui.add_number("seed", 0, step=1)
        lafan_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data/lafan1")
        lafan_clips = sorted(f[:-4] for f in os.listdir(lafan_dir) if f.endswith(".bvh")) if os.path.isdir(lafan_dir) else []
        g_iclip = server.gui.add_dropdown(
            "start clip", ("sample",) + tuple(lafan_clips),
            initial_value="dance1_subject1" if "dance1_subject1" in lafan_clips else "sample")
        g_init = server.gui.add_slider("init frame", 0, 7000, 1, 300)
        g_feed = server.gui.add_dropdown("feed back", ("xt", "x0", "mix", "final"), initial_value="xt")
        g_mix = server.gui.add_slider("mix (0=xt,1=x0)", 0.0, 1.0, 0.05, 0.5)
        g_nscale = server.gui.add_slider("noise scale", 0.0, 2.0, 0.05, 1.0)
        g_ncoh = server.gui.add_slider("noise coherence", 0.0, 0.99, 0.01, 0.0)
        g_root = server.gui.add_dropdown("root from", ("display", "x0", "none"), initial_value="display")
        g_clip = server.gui.add_slider("clip", 1.0, 10.0, 0.5, 4.0)
        g_auto = server.gui.add_checkbox("auto regenerate", True)
        g_gen = server.gui.add_button("Generate", color="blue")
    with server.gui.add_folder("Display"):
        g_decode = server.gui.add_dropdown(
            "joints from", DECODE_MODES, initial_value="position",
            hint="position: joint-position channels (spheres scatter freely). "
                 "rotation: FK from 6D rotations (bone lengths kept, skeleton twists).")
        g_show = server.gui.add_dropdown("show", ("xt", "x0", "xt + x0 ghost"), initial_value="xt")
        g_final = server.gui.add_checkbox(
            "overlay t=0", False,
            hint="Also run each frame's denoising to the end (same noise) and draw it in white; "
                 "the current-t skeleton turns yellow. Slower to generate (~3x).")
        g_jsize = server.gui.add_slider("joint size", 0.005, 0.2, 0.005, 0.04)
        g_joints = server.gui.add_checkbox("joints", True)
        g_reduced = server.gui.add_checkbox(
            "reduced skeleton", True,
            hint="Drop Spine, Spine1, Spine2 and both shoulders: torso bone Hips-Neck, arms attach at Neck.")
        g_bones = server.gui.add_checkbox("bones", True)
        g_bthick = server.gui.add_slider("bone width", 0.002, 0.05, 0.001, 0.008)
        g_grid = server.gui.add_checkbox("grid", True)
        g_bg = server.gui.add_rgb("background", (0, 0, 0))
    with server.gui.add_folder("Camera"):
        g_lock = server.gui.add_checkbox(
            "track joint", True,
            hint="Orbit / zoom / pan in the viewport freely; the view stays locked on the joint.")
        g_joint = server.gui.add_dropdown("joint", tuple(rt.joint_names), initial_value="RightHand")
        g_follow_y = server.gui.add_checkbox("follow height", True)
        g_az = server.gui.add_slider("azimuth", -180.0, 180.0, 1.0, 30.0)
        g_el = server.gui.add_slider("elevation", -89.0, 89.0, 1.0, 10.0)
        g_dist = server.gui.add_slider("distance", 0.1, 30.0, 0.05, 3.0)
        g_fov = server.gui.add_slider("fov", 10.0, 100.0, 1.0, 40.0)
        g_ortho = server.gui.add_checkbox(
            "orthographic", False,
            hint="No perspective. viser has no orthographic camera, so this is a telephoto "
                 "approximation (0.5° fov from far away, same framing as the fov/distance sliders).")
        g_reset = server.gui.add_button("reset view")
    with server.gui.add_folder("Playback"):
        g_play = server.gui.add_checkbox("playing", True, hint="space: play / pause")
        g_frame = server.gui.add_slider("frame", 0, 899, 1, 0)
        g_info = server.gui.add_markdown("")
        g_export = server.gui.add_button("Export MP4 (1080x1350)", color="green")
    plot = CurvePlot(server, color=(59, 108, 255))
    with server.gui.add_folder("Panel"):
        g_resetgui = server.gui.add_button("reset panel to defaults",
                                           hint="Forget the saved panel state (restart to apply).")

    # panel state is saved on every change and restored at start-up
    persisted = {k: v for k, v in locals().items()
                 if k.startswith("g_") and k not in ("g_frame", "g_play")
                 and type(v).__name__ in ("GuiSliderHandle", "GuiCheckboxHandle", "GuiDropdownHandle",
                                          "GuiNumberHandle", "GuiRgbHandle", "GuiTextHandle")}
    pstate = PersistentGui(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".cache/gui_state/exp2.json"),
                           persisted)
    pstate.restore()
    pstate.start_saving()
    g_resetgui.on_click(lambda _: (pstate.reset(), setattr(g_info, "content", "saved panel state cleared; restart to apply")))

    # -------------------------------------------------------------- scene
    # Joints and bones are both screen-facing flat circles (point clouds: unlit, no
    # shadows, no anti-aliased edges). Bones are drawn as densely sampled circles so
    # they share the joints' material and never show seams.
    WHITE, GHOST, YELLOW = (255, 255, 255), (110, 110, 110), (255, 214, 0)
    zeros_j = np.zeros((rt.J, 3), np.float32)

    def add_dots(name, color, size):
        return server.scene.add_point_cloud(name, zeros_j, color, point_size=size,
                                            point_shape="circle", point_shading="flat", precision="float32")

    HIDDEN_WHEN_REDUCED = ("Spine", "Spine1", "Spine2", "LeftShoulder", "RightShoulder")
    reduced_idx = np.array([i for i, n in enumerate(rt.joint_names) if n not in HIDDEN_WHEN_REDUCED])

    def _links(pairs):
        return np.array([[rt.joint_names.index(a), rt.joint_names.index(b)] for a, b in pairs])

    # Reduced bones: drop every bone touching a hidden joint, then bridge the gaps:
    # Hips-Spine2 (straight torso) and Neck-LeftArm / Neck-RightArm (arms hang from the neck).
    reduced_links = np.concatenate([
        np.array([l for l in rt.links
                  if rt.joint_names[l[0]] not in HIDDEN_WHEN_REDUCED
                  and rt.joint_names[l[1]] not in HIDDEN_WHEN_REDUCED]),
        _links([("Hips", "Neck"), ("Neck", "LeftArm"), ("Neck", "RightArm")]),
    ])

    class Skel:
        """One skeleton = joint dots + bone dots in a fixed colour."""
        def __init__(self, name, color):
            self.joints = add_dots(f"/{name}/joints", color, g_jsize.value)
            self.bones = add_dots(f"/{name}/bones", color, g_bthick.value)

        def show(self, pts: np.ndarray | None):
            on = pts is not None
            self.joints.visible = on and g_joints.value
            self.bones.visible = on and g_bones.value
            if self.joints.visible:
                shown = pts[reduced_idx] if g_reduced.value else pts
                self.joints.points = shown.astype(np.float32)
            if self.bones.visible:
                self.bones.points = bone_dots(pts, g_bthick.value,
                                              reduced_links if g_reduced.value else rt.links)

        def style(self):
            self.joints.point_size = g_jsize.value
            self.bones.point_size = g_bthick.value

    # drawn later = on top when overlapping at equal depth
    skel_final = Skel("final", WHITE)    # t=0 overlay
    skel_ghost = Skel("x0", GHOST)       # x0-prediction ghost
    skel_main = Skel("xt", WHITE)        # current t (white)
    skel_main_y = Skel("xt_y", YELLOW)   # current t when the t=0 overlay is on

    def bone_dots(j: np.ndarray, width: float, links: np.ndarray, max_pts: int = 20000) -> np.ndarray:
        a, b = j[links[:, 0]], j[links[:, 1]]
        lengths = np.linalg.norm(b - a, axis=1)
        step = max(width * 0.35, 1e-4)
        n = np.clip(np.ceil(lengths / step).astype(int) + 1, 2, None)
        if n.sum() > max_pts:
            n = np.maximum(2, (n * max_pts / n.sum()).astype(int))
        pts = [a[k] + np.linspace(0, 1, n[k])[:, None] * (b[k] - a[k]) for k in range(len(n))]
        return np.concatenate(pts).astype(np.float32)

    def apply_style(_=None):
        for sk in (skel_final, skel_ghost, skel_main, skel_main_y):
            sk.style()
        grid.visible = g_grid.value
        server.scene.set_background_image(np.full((4, 4, 3), g_bg.value, np.uint8))
        show_frame(state["frame"])

    # Space toggles playback. viser has no key-event API, but add_html injects raw
    # HTML, so an inline onerror handler registers a window keydown listener that
    # clicks the "playing" checkbox (which goes through the normal GUI update path).
    server.gui.add_html("""<img src="data:," style="display:none" onerror="
      if (!window.__vdcSpace) { window.__vdcSpace = true;
        window.addEventListener('keydown', function (e) {
          if (e.code !== 'Space' || e.repeat) return;
          var a = document.activeElement;
          if (a && (a.tagName === 'TEXTAREA' || (a.tagName === 'INPUT' && a.type !== 'checkbox'))) return;
          var el = Array.from(document.querySelectorAll('label, p, span, div'))
            .find(function (n) { return n.childElementCount === 0 && n.textContent.trim() === 'playing'; });
          if (el) { e.preventDefault(); e.stopPropagation(); el.click(); }
        }, true);
      }">""")

    def cam() -> TrackCam:
        return TrackCam(joint=rt.joint_names.index(g_joint.value), azimuth=g_az.value,
                        elevation=g_el.value, distance=g_dist.value, fov=g_fov.value)

    # ------------------------------------------------------------- tracking
    def anchor(res, i: int) -> np.ndarray:
        """Tracked joint position for frame i (vertical frozen at frame 0 if not following height)."""
        seq = res.joints_x0 if g_show.value == "x0" else res.joints_xt
        j = rt.joint_names.index(g_joint.value)
        a = seq[i, j].astype(np.float64).copy()
        if not g_follow_y.value:
            a[1] = seq[0, j, 1]
        return a

    # ------------------------------------------------------------- camera
    # The camera is owned by the viewer: the server only sets it when the user
    # moves an orbit slider in the panel (or on connect / reset). Viewport orbit /
    # zoom (including the controls' inertia) is only read back into the sliders.
    ignore_until: dict[int, float] = {}
    CONNECT_GRACE_S = 1.0

    # Orthographic = telephoto approximation: the real camera uses ORTHO_FOV and
    # sits `dist_scale()` times farther away, so the distance slider keeps meaning
    # "framing as seen with the fov slider" in both modes.
    ORTHO_FOV_DEG = 0.5

    def real_fov_deg() -> float:
        return ORTHO_FOV_DEG if g_ortho.value else g_fov.value

    def dist_scale() -> float:
        if not g_ortho.value:
            return 1.0
        return np.tan(np.deg2rad(g_fov.value) / 2) / np.tan(np.deg2rad(ORTHO_FOV_DEG) / 2)

    def push_camera(force: bool = False):
        k = dist_scale()
        real_dist = max(g_dist.value, 0.05) * k   # typing "0.5" passes through "0"
        offset, _ = TrackCam(azimuth=g_az.value, elevation=g_el.value,
                             distance=real_dist).pose(np.zeros((rt.J, 3)))
        for cid, c in server.get_clients().items():
            look = np.zeros(3) if force else np.asarray(c.camera.look_at)
            c.camera.fov = np.deg2rad(real_fov_deg())
            # near > ~1 hides viser's background image; 1.0 still gives mm depth precision at ~250 m
            c.camera.near = 1.0 if g_ortho.value else 0.01
            c.camera.far = real_dist * 4 + 1000.0
            try:
                c.camera.position = look + offset
                c.camera.look_at = look
            except ValueError:   # transient degenerate pose
                pass

    def on_client(client: viser.ClientHandle):
        cid = client.client_id

        @client.camera.on_update
        def _(camera: viser.CameraHandle):
            if time.time() < ignore_until.get(cid, 0.0):
                return
            orb = orbit_from(np.asarray(camera.position), np.asarray(camera.look_at))
            if orb is None:
                return
            az, el, dist = orb
            dist = dist / dist_scale()
            if np.allclose((az, el, dist), (g_az.value, g_el.value, g_dist.value), atol=1e-2):
                return
            g_az.value = float(np.clip(az, g_az.min, g_az.max))
            g_el.value = float(np.clip(el, g_el.min, g_el.max))
            g_dist.value = float(np.clip(dist, g_dist.min, g_dist.max))

        ignore_until[cid] = time.time() + CONNECT_GRACE_S
        push_camera(force=True)

    server.on_client_connect(on_client)

    @g_reset.on_click
    def _(_):
        g_az.value, g_el.value, g_dist.value, g_fov.value = 30.0, 10.0, 3.0, 40.0
        push_camera(force=True)

    def show_frame(i: int):
        res = state["res"]
        if res is None:
            return
        i = int(np.clip(i, 0, len(res.levels) - 1))
        mode = g_show.value
        main = res.joints_x0[i] if mode == "x0" else res.joints_xt[i]
        ghost_vis = mode == "xt + x0 ghost"
        final_vis = g_final.value and res.joints_final is not None
        a = anchor(res, i) if g_lock.value else np.zeros(3)
        main = main - a
        with server.atomic():
            grid.position = -a
            skel_main.show(None if final_vis else main)
            skel_main_y.show(main if final_vis else None)
            skel_ghost.show(res.joints_x0[i] - a if ghost_vis else None)
            skel_final.show(res.joints_final[i] - a if final_vis else None)
        g_info.content = f"frame **{i}** / {len(res.levels) - 1} &nbsp; τ = **{res.levels[i]:.2f}** / {T}"

    def schedule():
        if g_stype.value == "ramp":
            return RampSchedule(fade_in=g_rfade.value, start=g_rstart.value, peak=g_rpeak.value, base=g_rbase.value,
                                curve=g_rcurve.value, power=g_rpower.value)
        if g_stype.value == "pulses":
            return PulseSchedule(frames=g_pframes.value, count=int(g_pcount.value), peak=g_ppeak.value,
                                 attack=int(g_pattack.value), decay=int(g_pdecay.value), base=g_pbase.value)
        return DipSchedule(high=g_high.value, low=g_low.value, center=g_center.value,
                           half_width=g_width.value, sharpness=g_sharp.value)

    def sched_visibility(_=None):
        t = g_stype.value
        for h in (g_pframes, g_pcount, g_ppeak, g_pattack, g_pdecay, g_pbase):
            h.visible = t == "pulses"
        for h in (g_rfade, g_rstart, g_rpeak, g_rcurve, g_rpower, g_rbase):
            h.visible = t == "ramp"
        for h in (g_high, g_low, g_center, g_width, g_sharp):
            h.visible = t == "dip"
        g_pcount.disabled = bool(g_pframes.value.strip())
    g_stype.on_update(sched_visibility)
    g_pframes.on_update(sched_visibility)
    sched_visibility()

    def params() -> GenParams:
        return GenParams(num_frames=int(g_frames.value), seed=int(g_seed.value),
                         init_clip="" if g_iclip.value == "sample" else g_iclip.value, init_frame=int(g_init.value),
                         feed=g_feed.value, feed_mix=g_mix.value, noise_scale=g_nscale.value,
                         noise_coherence=g_ncoh.value, root_source=g_root.value, clip=g_clip.value,
                         compute_final=g_final.value)

    def update_plot(levels):
        plot.set_values(levels, vmax=float(T))

    def regenerate(_=None):
        with lock:
            g_gen.disabled = True
            levels = schedule().levels(int(g_frames.value))
            update_plot(levels)
            t0 = time.time()
            res = rt.generate(levels, params(), decode_mode=g_decode.value)
            state["res"] = res
            g_frame.max = len(levels) - 1
            g_gen.disabled = False
            print(f"generated {len(levels)} frames in {time.time() - t0:.2f}s", flush=True)
        show_frame(state["frame"])

    for h in (g_frames, g_stype, g_pframes, g_pcount, g_ppeak, g_pattack, g_pdecay, g_pbase, g_iclip,
              g_rfade, g_rstart, g_rpeak, g_rcurve, g_rpower, g_rbase,
              g_high, g_low, g_center, g_width, g_sharp, g_seed, g_init, g_feed, g_mix,
              g_nscale, g_ncoh, g_root, g_clip):
        h.on_update(lambda _: g_auto.value and regenerate())
    g_gen.on_click(regenerate)
    for h in (g_jsize, g_bthick, g_grid, g_bg):
        h.on_update(apply_style)
    def redecode(_=None):
        with lock:
            if state["res"] is not None:
                rt.decode_result(state["res"], g_decode.value)
        show_frame(state["frame"])
    g_decode.on_update(redecode)

    def on_final(_):
        res = state["res"]
        if g_final.value and res is not None and res.joints_final is None:
            regenerate()
        else:
            show_frame(state["frame"])
    g_final.on_update(on_final)

    for h in (g_show, g_joints, g_reduced, g_bones, g_lock, g_joint, g_follow_y):
        h.on_update(lambda _: show_frame(state["frame"]))
    g_ortho.on_update(lambda _: push_camera())
    for h in (g_az, g_el, g_dist, g_fov):
        # only when the user drags the slider (programmatic sets have no client)
        h.on_update(lambda e: e.client is not None and push_camera())

    def on_frame(_):
        if not state["playing"]:
            state["frame"] = int(g_frame.value)
            show_frame(state["frame"])
    g_frame.on_update(on_frame)
    g_play.on_update(lambda _: state.update(playing=g_play.value))

    # -------------------------------------------------------------- export
    def export(event: viser.GuiEvent):
        client = event.client
        res = state["res"]
        if client is None or res is None:
            return
        g_play.value = False
        state["playing"] = False
        os.makedirs(OUT_DIR, exist_ok=True)
        stamp = dt.datetime.now().strftime("%Y%m%d_%H%M%S")
        path = os.path.join(OUT_DIR, f"exp2_{stamp}.mp4")
        c = client.camera
        cam_pos, cam_wxyz, cam_fov = np.array(c.position), np.array(c.wxyz), float(c.fov)
        meta = {"schedule": asdict(schedule()), "gen": asdict(params()),
                "camera": {**asdict(cam()), "track": g_lock.value, "orthographic": g_ortho.value,
                           "follow_height": g_follow_y.value, "position": cam_pos.tolist(),
                           "wxyz": cam_wxyz.tolist(), "fov_rad": cam_fov},
                "decode": g_decode.value, "show": g_show.value, "overlay_t0": g_final.value, "joints": g_joints.value, "reduced_skeleton": g_reduced.value, "bones": g_bones.value, "joint_size": g_jsize.value, "bone_width": g_bthick.value, "grid": g_grid.value, "background": list(g_bg.value)}
        with open(path.replace(".mp4", ".json"), "w") as f:
            json.dump(meta, f, indent=2)
        g_export.disabled = True
        writer = imageio.get_writer(path, fps=FPS, codec="libx264", quality=8, macro_block_size=1)
        try:
            n = len(res.levels)
            for i in range(n):
                show_frame(i)
                img = client.get_render(VIDEO_H, VIDEO_W, position=cam_pos, wxyz=cam_wxyz,
                                        fov=cam_fov, transport_format="png")
                if img.shape[-1] == 4:
                    a = img[..., 3:4].astype(np.float32) / 255.0
                    img = img[..., :3] * a + np.asarray(g_bg.value, np.float32) * (1 - a)
                writer.append_data(img[..., :3].astype(np.uint8))
                if i % 30 == 0:
                    g_info.content = f"exporting {i}/{n} ..."
        except Exception as e:  # e.g. the browser tab closed mid-export
            writer.close()
            g_export.disabled = False
            g_info.content = f"export failed: {e}"
            print("export failed:", repr(e), flush=True)
            return
        writer.close()
        g_export.disabled = False
        g_info.content = f"saved `{path}`"
        print("saved", path)
    g_export.on_click(export)

    # -------------------------------------------------------------- loop
    regenerate()
    apply_style()
    print("open http://localhost:8080")
    while True:
        t0 = time.time()
        if state["playing"] and state["res"] is not None:
            state["frame"] = (state["frame"] + 1) % len(state["res"].levels)
            show_frame(state["frame"])
            g_frame.value = state["frame"]
            if state["frame"] % 6 == 0:
                plot.set_cursor(state["frame"])
        time.sleep(max(0.0, 1.0 / FPS - (time.time() - t0)))


if __name__ == "__main__":
    main()
